/**
 * Returns the category associated with a given notification type.
 * @param {string} type 
 * @returns {string|null}
 */
export function getCategoryForType(type) {
  for (const category of NOTIFICATION_CATEGORIES) {
    if (NOTIFICATION_TYPES[category] && NOTIFICATION_TYPES[category][type]) {
      return category;
    }
  }
  return null;
}

/**
 * Returns all notification types belonging to a given category.
 * @param {string} category 
 * @returns {string[]}
 */
export function getTypesForCategory(category) {
  if (NOTIFICATION_TYPES[category]) {
    return Object.keys(NOTIFICATION_TYPES[category]);
  }
  return [];
}
